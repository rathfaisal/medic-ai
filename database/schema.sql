-- MEDIC-AI PostgreSQL reference schema
-- The ASP.NET Core application creates the development schema through EF Core EnsureCreated.
-- This file documents the intended relational structure for review and Chapter 6 evidence.

CREATE SCHEMA IF NOT EXISTS medic_ai;

CREATE TABLE IF NOT EXISTS medic_ai.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(191) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role varchar(30) NOT NULL CHECK (role IN ('Patient','Staff','Doctor','Admin')),
    status varchar(30) NOT NULL DEFAULT 'Active',
    last_login_at timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.patient_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE REFERENCES medic_ai.users(id) ON DELETE CASCADE,
    full_name varchar(150) NOT NULL,
    date_of_birth date NOT NULL,
    gender varchar(30),
    phone varchar(30) NOT NULL,
    address varchar(255),
    allergies text,
    existing_conditions text,
    emergency_contact varchar(150)
);

CREATE TABLE IF NOT EXISTS medic_ai.staff_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE REFERENCES medic_ai.users(id) ON DELETE CASCADE,
    full_name varchar(150) NOT NULL,
    position varchar(100) NOT NULL,
    phone varchar(30)
);

CREATE TABLE IF NOT EXISTS medic_ai.doctor_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL UNIQUE REFERENCES medic_ai.users(id) ON DELETE CASCADE,
    full_name varchar(150) NOT NULL,
    registration_no varchar(80) NOT NULL UNIQUE,
    speciality varchar(120),
    is_available boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS medic_ai.appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES medic_ai.patient_profiles(id),
    assigned_doctor_id integer NULL REFERENCES medic_ai.doctor_profiles(id) ON DELETE SET NULL,
    appointment_date_time timestamptz NOT NULL,
    service_type varchar(100) NOT NULL,
    reason varchar(500),
    status varchar(30) NOT NULL DEFAULT 'Booked',
    created_by_user_id integer NOT NULL REFERENCES medic_ai.users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.symptom_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES medic_ai.patient_profiles(id),
    appointment_id bigint UNIQUE NULL REFERENCES medic_ai.appointments(id) ON DELETE SET NULL,
    main_symptom varchar(255) NOT NULL,
    duration_value integer NOT NULL,
    duration_unit varchar(30) NOT NULL,
    pain_severity smallint NOT NULL CHECK (pain_severity BETWEEN 0 AND 10),
    additional_symptoms text,
    existing_conditions_snapshot text,
    consent_confirmed boolean NOT NULL,
    fever boolean NOT NULL DEFAULT false,
    vomiting boolean NOT NULL DEFAULT false,
    dizziness boolean NOT NULL DEFAULT false,
    worsening_symptoms boolean NOT NULL DEFAULT false,
    severe_breathing_difficulty boolean NOT NULL DEFAULT false,
    chest_pain boolean NOT NULL DEFAULT false,
    loss_of_consciousness boolean NOT NULL DEFAULT false,
    major_bleeding boolean NOT NULL DEFAULT false,
    seizure boolean NOT NULL DEFAULT false,
    severe_allergic_reaction boolean NOT NULL DEFAULT false,
    sudden_severe_weakness boolean NOT NULL DEFAULT false,
    submitted_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.ai_model_versions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_name varchar(80) NOT NULL UNIQUE,
    algorithm varchar(80) NOT NULL,
    feature_schema_json jsonb NOT NULL,
    metrics_json jsonb,
    file_path varchar(255) NOT NULL,
    is_active boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.triage_assessments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL UNIQUE REFERENCES medic_ai.symptom_submissions(id) ON DELETE CASCADE,
    model_version_id integer NULL REFERENCES medic_ai.ai_model_versions(id) ON DELETE SET NULL,
    urgency_level varchar(30) NOT NULL,
    source varchar(30) NOT NULL,
    confidence_score numeric(5,4),
    rule_flags_json jsonb,
    explanation text NOT NULL,
    original_urgency varchar(30) NOT NULL,
    overridden_urgency varchar(30),
    overridden_by_user_id integer NULL REFERENCES medic_ai.users(id) ON DELETE SET NULL,
    override_reason varchar(500),
    low_confidence_flag boolean NOT NULL DEFAULT false,
    review_required boolean NOT NULL DEFAULT false,
    assessed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.queue_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES medic_ai.patient_profiles(id),
    appointment_id bigint UNIQUE NULL REFERENCES medic_ai.appointments(id) ON DELETE SET NULL,
    assessment_id bigint UNIQUE NULL REFERENCES medic_ai.triage_assessments(id) ON DELETE SET NULL,
    check_in_time timestamptz NOT NULL DEFAULT now(),
    priority_score numeric(8,2) NOT NULL,
    confirmed_urgency varchar(30) NOT NULL,
    queue_status varchar(30) NOT NULL DEFAULT 'Waiting',
    handled_by_staff_id integer NULL REFERENCES medic_ai.staff_profiles(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.consultations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES medic_ai.patient_profiles(id),
    doctor_id integer NOT NULL REFERENCES medic_ai.doctor_profiles(id),
    appointment_id bigint UNIQUE NULL REFERENCES medic_ai.appointments(id) ON DELETE SET NULL,
    clinical_notes text NOT NULL,
    diagnosis text,
    treatment_plan text,
    follow_up_date date,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.emergency_alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES medic_ai.patient_profiles(id),
    assessment_id bigint NOT NULL UNIQUE REFERENCES medic_ai.triage_assessments(id) ON DELETE CASCADE,
    warning_reason text NOT NULL,
    status varchar(40) NOT NULL DEFAULT 'Created',
    assigned_role varchar(30) NOT NULL DEFAULT 'Staff',
    created_at timestamptz NOT NULL DEFAULT now(),
    acknowledged_by_user_id integer NULL REFERENCES medic_ai.users(id) ON DELETE SET NULL,
    acknowledged_at timestamptz,
    acknowledgement_notes text,
    resolution_notes text,
    resolved_by_user_id integer NULL REFERENCES medic_ai.users(id) ON DELETE SET NULL,
    resolved_at timestamptz
);

CREATE TABLE IF NOT EXISTS medic_ai.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES medic_ai.users(id) ON DELETE CASCADE,
    appointment_id bigint NULL REFERENCES medic_ai.appointments(id) ON DELETE SET NULL,
    channel varchar(30) NOT NULL DEFAULT 'InApp',
    message text NOT NULL,
    delivery_status varchar(30) NOT NULL DEFAULT 'Pending',
    scheduled_at timestamptz,
    sent_at timestamptz,
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NULL REFERENCES medic_ai.users(id) ON DELETE SET NULL,
    action varchar(100) NOT NULL,
    entity_type varchar(80),
    entity_id bigint,
    details_json jsonb,
    ip_address varchar(45),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS medic_ai.red_flag_rules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code varchar(80) NOT NULL UNIQUE,
    rule_name varchar(150) NOT NULL,
    condition_json jsonb NOT NULL,
    warning_message text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    approved_by varchar(150),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_appointments_datetime ON medic_ai.appointments(appointment_date_time);
CREATE INDEX IF NOT EXISTS ix_queue_active ON medic_ai.queue_entries(queue_status, confirmed_urgency, priority_score DESC, check_in_time);
CREATE INDEX IF NOT EXISTS ix_alert_status ON medic_ai.emergency_alerts(status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_audit_created ON medic_ai.audit_logs(created_at DESC);
